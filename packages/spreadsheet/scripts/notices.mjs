/**
 * Writes THIRD-PARTY-NOTICES.md: every package the library builds include,
 * with its version, licence and licence text, as those licences ask of
 * anything that ships them. The packages are read from the builds' source
 * maps, so the list is what is actually bundled, lazily loaded parts
 * included.
 *
 * Needs `npm run build:lib` first.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
/** Where the workspace's packages are installed. */
const workspace = fileURLToPath(new URL('../../..', import.meta.url));
const BUILDS = [
  ['dist/react', 'the React build'],
  ['dist/standalone', 'the standalone build'],
];

const mapsIn = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? mapsIn(join(dir, e.name)) : e.name.endsWith('.js.map') ? [join(dir, e.name)] : []));

/** The directory of the package a bundled file belongs to, or undefined for the editor's own files. */
function packageDir(file) {
  const parts = file.split(sep);
  const at = parts.lastIndexOf('node_modules');
  if (at < 0) return undefined;
  const length = parts[at + 1]?.startsWith('@') ? 2 : 1;
  return parts.slice(0, at + 1 + length).join(sep);
}

/** dir → the builds it is in. */
const packages = new Map();
for (const [dir, build] of BUILDS) {
  const path = join(root, dir);
  if (!existsSync(path)) {
    console.error('Build the library first: npm run build:lib');
    process.exit(1);
  }
  for (const map of mapsIn(path)) {
    // Sources are relative to wherever each part was built from, so they are read from node_modules onwards.
    for (const source of JSON.parse(readFileSync(map, 'utf8')).sources ?? []) {
      const at = source.indexOf('node_modules/');
      const pkg = at < 0 ? undefined : packageDir(join(workspace, ...source.slice(at).split('/')));
      if (pkg) packages.set(pkg, (packages.get(pkg) ?? new Set()).add(build));
    }
  }
}

const licenceOf = (meta) =>
  typeof meta.license === 'string' ? meta.license : (meta.license?.type ?? meta.licenses?.map((l) => l.type ?? l).join(' OR ') ?? 'not stated');
const homeOf = (meta) => meta.homepage ?? (typeof meta.repository === 'string' ? meta.repository : meta.repository?.url)?.replace(/^git\+/, '');
const licenceFile = (dir) => readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));

const entries = [...packages]
  .map(([dir, builds]) => ({ dir, builds, meta: JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) }))
  .sort((a, b) => a.meta.name.localeCompare(b.meta.name) || a.meta.version.localeCompare(b.meta.version));

const sections = entries.map(({ dir, builds, meta }) => {
  const file = licenceFile(dir);
  const text = file ? readFileSync(join(dir, file), 'utf8').trim() : `The package has no licence file; its package.json gives its licence as ${licenceOf(meta)}.`;
  const home = homeOf(meta);
  return [
    `## ${meta.name} ${meta.version}`,
    '',
    `Licence: ${licenceOf(meta)}. In ${[...builds].sort().join(' and ')}.${home ? ` ${home}` : ''}`,
    '',
    '````text',
    text,
    '````',
  ].join('\n');
});

const out = [
  '# Third-party notices',
  '',
  'The workbook editor includes the open-source packages below, each with its',
  'licence text. The React build leaves React itself to the host app; the',
  'standalone build includes it. Generated by `npm run notices` from the',
  "library builds' source maps.",
  '',
  ...sections.flatMap((s) => [s, '']),
].join('\n');
writeFileSync(join(root, 'THIRD-PARTY-NOTICES.md'), out);
console.log(`Wrote THIRD-PARTY-NOTICES.md: ${entries.length} packages.`);
