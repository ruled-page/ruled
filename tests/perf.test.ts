import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { WorkbookSession } from '../src/core/session';
import { sample, SAMPLES } from './helpers';

/**
 * Time budgets, about three times what a 2024 laptop takes, so that a slower
 * CI machine passes but a change that makes opening, calculating or saving
 * much slower doesn't. CI runs this on its own (npm run test:perf), since
 * coverage instrumentation slows everything down.
 */
const BUDGET_MS = { open: 3500, edit: 100, editLive: 1500, engine: 15_000, save: 4500 };

// big.xlsx is generated by `npm run samples` and not committed.
describe.skipIf(!existsSync(join(SAMPLES, 'big.xlsx')))('big.xlsx (100k rows)', () => {
  const mem = () => Math.round(process.memoryUsage().heapUsed / 1e6);

  it('opens with live recalculation off, and edits and saves quickly', () => {
    const bytes = sample('big.xlsx');
    const t0 = performance.now();
    const s = WorkbookSession.open(bytes, 'big.xlsx');
    const report = s.ensureEngine();
    const t1 = performance.now();
    const r = s.apply({ type: 'input', sheet: 0, row: 1, col: 5, text: '1000' });
    const t2 = performance.now();
    const out = s.save();
    const t3 = performance.now();
    console.log({ mode: 'off', openMs: Math.round(t1 - t0), editMs: Math.round(t2 - t1), saveMs: Math.round(t3 - t2), heapMB: mem(), outMB: (out.length / 1e6).toFixed(1) });
    expect(report.off).toBe(true);
    expect(r.updates.length).toBe(1);
    expect(t1 - t0, 'open').toBeLessThan(BUDGET_MS.open);
    expect(t2 - t1, 'edit').toBeLessThan(BUDGET_MS.edit);
    expect(t3 - t2, 'save').toBeLessThan(BUDGET_MS.save);
  });

  it('recalculates live when asked to', () => {
    const bytes = sample('big.xlsx');
    const t0 = performance.now();
    const s = WorkbookSession.open(bytes, 'big.xlsx', 'en-US', { recalc: 'on' });
    const t1 = performance.now();
    const report = s.ensureEngine();
    const t2 = performance.now();
    const r = s.apply({ type: 'input', sheet: 0, row: 1, col: 5, text: '1000' });
    const t3 = performance.now();
    const out = s.save();
    const t4 = performance.now();
    console.log({
      mode: 'on',
      cells: s.model.sheets[0].scan!.grid.cols.length,
      openMs: Math.round(t1 - t0),
      engineMs: Math.round(t2 - t1),
      editMs: Math.round(t3 - t2),
      saveMs: Math.round(t4 - t3),
      heapMB: mem(),
      formulas: report.formulaCells,
      live: report.liveCells,
      updates: r.updates.length,
      outMB: (out.length / 1e6).toFixed(1),
    });
    expect(report.mismatched).toBe(0);
    expect(r.updates.length).toBeGreaterThanOrEqual(5);
    expect(t1 - t0, 'open').toBeLessThan(BUDGET_MS.open);
    expect(t2 - t1, 'engine').toBeLessThan(BUDGET_MS.engine);
    expect(t3 - t2, 'edit').toBeLessThan(BUDGET_MS.editLive);
    expect(t4 - t3, 'save').toBeLessThan(BUDGET_MS.save);
  });
});
